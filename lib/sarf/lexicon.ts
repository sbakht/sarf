export function rootArabic(entry: RootEntry): string {
  return entry.letters.join("");
}

export function getRoot(id: string): RootEntry {
  const found = ROOTS.find((root) => root.id === id);
  if (!found) throw new Error(`Unknown root ${id}`);
  return found;
}

export function soundRoots(): RootEntry[] {
  return ROOTS.filter((root) => root.weakness === "sound");
}

export function rootsByWeakness(type: RootEntry["weakness"]): RootEntry[] {
  return ROOTS.filter((root) => root.weakness === type);
}
